import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = ROOT / "config"
SOURCES = ["user.js", "diet-safe.js", "blocker.js", "no-phone-home.js"]
DEV_LISTS = "/home/USER/Projects/browser/config/lists/"
PKG_LISTS = "/usr/share/obscurant/lists/"
WIN_LISTS = "chrome://browser/content/lists/"
SKIP = ("browser.aboutwelcome.enabled",)


def convert(text, lists_dir):
    out = []
    for line in text.splitlines():
        if line.startswith("user_pref("):
            if any(f'"{name}"' in line for name in SKIP):
                continue
            line = "pref(" + line[len("user_pref("):]
            line = line.replace(DEV_LISTS, lists_dir)
        out.append(line)
    return "\n".join(out)


def build(lists_dir):
    parts = ["// Generated by tools/make_defaults.py from config/*.js. Do not edit.\n"]
    for name in SOURCES:
        parts.append(f"// --- {name}\n" + convert((CFG / name).read_text(), lists_dir) + "\n")
    return "\n".join(parts)


(ROOT / "pkg" / "obscurant.js").write_text(build(PKG_LISTS))
(ROOT / "pkg" / "obscurant-portable.js").write_text(build(WIN_LISTS))
WIN_EXTRA = """
// --- Windows
pref("general.useragent.override", "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:153.0) Gecko/20100101 Firefox/153.0");
pref("browser.tabs.unloadOnLowMemory", true);
"""
(ROOT / "pkg" / "obscurant-win.js").write_text(build(WIN_LISTS) + WIN_EXTRA)
dev = ROOT / "src" / "obj-v1" / "dist" / "bin" / "browser" / "defaults" / "preferences"
dev.mkdir(parents=True, exist_ok=True)
(dev / "obscurant.js").write_text(build(DEV_LISTS))
n = len(re.findall(r"^pref\(", (ROOT / "pkg" / "obscurant.js").read_text(), re.M))
print(f"wrote pkg/obscurant.js and dev defaults: {n} prefs")
