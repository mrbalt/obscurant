#!/usr/bin/env python3
# Writes the Android theme sources from the desktop palettes in tools/make_themes.py.
# usage: make_android_themes.py <firefox source dir>
import ast, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1]
APP = os.path.join(SRC, "mobile", "android", "fenix", "app", "src", "main")

tree = ast.parse(open(os.path.join(HERE, "make_themes.py")).read())
PALETTES = next(ast.literal_eval(n.value) for n in tree.body
                if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "PALETTES")


def rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def lum(h):
    r, g, b = rgb(h)
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255


def mix(a, b, t):
    return "#" + "".join("%02x" % round(x * t + y * (1 - t)) for x, y in zip(rgb(a), rgb(b)))


def style_name(i):
    return "ObscurantOverlay%d" % i


kt = []
xml = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/make_android_themes.py. Do not edit. -->", "<resources>"]
for i, (name, frame, toolbar, field, text, sub, accent, border) in enumerate(PALETTES):
    light = lum(frame) > 0.5
    on_accent = "#000000" if lum(accent) > 0.45 else "#ffffff"
    soft = mix(accent, toolbar, 0.25)
    c = lambda h: "0xFF" + h[1:].upper()
    kt.append('    ObscurantPalette("%s", %s, %s, R.style.%s),' % (
        name, "true" if light else "false",
        ", ".join(c(h) for h in (frame, toolbar, field, text, sub, accent, on_accent, soft, border)), style_name(i)))
    items = {
        "colorPrimary": accent, "colorOnPrimary": on_accent, "colorPrimaryContainer": soft, "colorOnPrimaryContainer": text,
        "colorSecondary": sub, "colorOnSecondary": frame, "colorSecondaryContainer": field, "colorOnSecondaryContainer": text,
        "colorTertiary": accent, "colorOnTertiary": on_accent, "colorTertiaryContainer": soft, "colorOnTertiaryContainer": text,
        "android:colorBackground": frame, "colorOnBackground": text, "android:windowBackground": frame,
        "colorSurface": toolbar, "colorOnSurface": text, "colorSurfaceVariant": field, "colorOnSurfaceVariant": sub,
        "colorOutline": border, "colorOutlineVariant": border, "colorSurfaceBright": field, "colorSurfaceDim": frame,
        "colorSurfaceContainerLowest": toolbar, "colorSurfaceContainerLow": toolbar, "colorSurfaceContainer": toolbar,
        "colorSurfaceContainerHigh": field, "colorSurfaceContainerHighest": field,
        "android:textColorPrimary": text, "android:textColorSecondary": sub, "android:colorAccent": accent,
        "android:textColorLink": accent,
    }
    xml.append('    <style name="%s" parent="">' % style_name(i))
    xml += ['        <item name="%s">%s</item>' % kv for kv in items.items()]
    xml.append("    </style>")
xml.append("</resources>")
open(os.path.join(APP, "res", "values", "obscurant_themes.xml"), "w").write("\n".join(xml) + "\n")

header = '''/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// Generated by tools/make_android_themes.py. Do not edit.

package org.mozilla.fenix.theme

import org.mozilla.fenix.R

internal val obscurantPalettes: List<ObscurantPalette> = listOf(
'''
open(os.path.join(APP, "java", "org", "mozilla", "fenix", "theme", "ObscurantPalettes.kt"), "w").write(header + "\n".join(kt) + "\n)\n")
print(len(PALETTES), "themes written")
